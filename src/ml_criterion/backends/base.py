from dataclasses import dataclass
from typing import Protocol


@dataclass
class RunContext:
    connection: object
    schema: str
    spec: dict
    memory_mb: int


class BackendAdapter(Protocol):
    def validate(self, context: RunContext) -> None: ...
    def prepare(self, context: RunContext) -> None: ...
    def train(self, context: RunContext) -> None: ...
    def predict(self, context: RunContext) -> None: ...
    def persist_results(self, context: RunContext) -> None: ...
    def collect_diagnostics(self, context: RunContext) -> dict: ...
    def cleanup(self) -> None: ...
